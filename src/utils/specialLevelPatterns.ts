const KEYS = Object.keys(P);

// Levels the player asked to be replaced
export const SPECIAL_LEVELS = [
  16, 20, 26, 60, 67, 70, 110, 115, 120, 150, 160, 200,
  204, 250, 290, 300, 340, 350, 380, 390, 430,
];

/**
 * Returns a replacement pattern if this level (or its repeat past level 500)
 * is one the player wants changed.
 */
export function getSpecialPattern(level: number): number[][] | null {
  const base = ((level - 1) % 500) + 1;
  const idx = SPECIAL_LEVELS.indexOf(base);
  if (idx === -1) return null;
  // Vary across the 500-level cycles so repeats also feel different
  const cycle = Math.floor((level - 1) / 500);
  return P[KEYS[(idx + cycle * 5) % KEYS.length]];
}
